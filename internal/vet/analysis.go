package vet

import (
	"go/ast"
	"go/token"
	"go/types"
	"maps"
	"path/filepath"
	"slices"
	"strings"

	"golang.org/x/tools/go/ssa"
)

// generatedHeader starts the comment of a file kanna-orm generated.
const generatedHeader = "Code generated by kanna-orm. DO NOT EDIT."

// analysis reads the functions of the packages vet checks, and what they call.
type analysis struct {
	prog *ssa.Program
	fset *token.FileSet
	// generatedFiles are the files kanna-orm generated, among those vet read the syntax of.
	generatedFiles map[string]bool
	// callAt is where a report of a call is: its method, by the left parenthesis of the call.
	callAt map[token.Pos]token.Pos
	// repositories are the types of the repositories kanna-orm generated.
	repositories []*types.Named

	memo    map[string]*result
	tracks  map[*ssa.Alloc]bool
	musts   map[*ssa.BasicBlock]bool
	impls   map[string][]*ssa.Function
	envs    map[*ssa.Function][]value
	reports []report
}

// report is a call that fails on every path.
type report struct {
	pos  token.Pos
	in   string
	fail *failed
}

func newAnalysis(prog *ssa.Program, fset *token.FileSet, files []*ast.File) *analysis {
	a := &analysis{
		prog: prog, fset: fset, generatedFiles: map[string]bool{}, callAt: map[token.Pos]token.Pos{},
		memo: map[string]*result{}, tracks: map[*ssa.Alloc]bool{}, musts: map[*ssa.BasicBlock]bool{},
		impls: map[string][]*ssa.Function{}, envs: map[*ssa.Function][]value{},
	}
	for _, f := range files {
		name := fset.Position(f.Package).Filename
		if isGenerated(f) {
			a.generatedFiles[name] = true
			continue
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if c, ok := n.(*ast.CallExpr); ok {
				a.callAt[c.Lparen] = callee(c.Fun).Pos()
			}
			return true
		})
	}
	return a
}

func isGenerated(f *ast.File) bool {
	for _, c := range f.Comments {
		if c.Pos() > f.Package {
			break
		}
		if strings.Contains(c.Text(), generatedHeader) {
			return true
		}
	}
	return false
}

// callee is the expression naming what a call calls: the method of a selector, the function of an instantiation.
func callee(e ast.Expr) ast.Expr {
	switch e := e.(type) {
	case *ast.ParenExpr:
		return callee(e.X)
	case *ast.SelectorExpr:
		return e.Sel
	case *ast.IndexExpr:
		return callee(e.X)
	case *ast.IndexListExpr:
		return callee(e.X)
	}
	return e
}

// findRepositories keeps the types of the repositories kanna-orm generated in pkgs.
func (a *analysis) findRepositories(pkgs []*types.Package) {
	for _, pkg := range pkgs {
		scope := pkg.Scope()
		for _, name := range scope.Names() {
			tn, ok := scope.Lookup(name).(*types.TypeName)
			if !ok || tn.IsAlias() {
				continue
			}
			file := a.fset.Position(tn.Pos()).Filename
			if !a.generatedFiles[file] || filepath.Base(file) != "repository_gen.go" {
				continue
			}
			if n, ok := tn.Type().(*types.Named); ok {
				if _, ok := n.Underlying().(*types.Struct); ok {
					a.repositories = append(a.repositories, n)
				}
			}
		}
	}
}

// generated reports whether kanna-orm generated fn.
func (a *analysis) generated(fn *ssa.Function) bool {
	if o := fn.Origin(); o != nil {
		fn = o
	}
	for fn.Parent() != nil {
		fn = fn.Parent()
	}
	if fn.Pos() == token.NoPos {
		return false
	}
	return a.generatedFiles[a.fset.Position(fn.Pos()).Filename]
}

// callPos is where vet reports a call: at the name of what it calls.
func (a *analysis) callPos(instr ssa.CallInstruction) token.Pos {
	p := instr.Common().Pos()
	if at, ok := a.callAt[p]; ok {
		return at
	}
	return p
}

// tracked reports whether vet follows what the allocation a holds: a scope or a change set, or an array of them or
// of strings, which nothing but loads and stores reach, and closures that only read it.
func (a *analysis) tracked(alloc *ssa.Alloc) bool {
	if t, ok := a.tracks[alloc]; ok {
		return t
	}
	t := trackable(alloc)
	a.tracks[alloc] = t
	return t
}

func trackable(alloc *ssa.Alloc) bool {
	t := deref(alloc.Type())
	if arr, ok := t.Underlying().(*types.Array); ok {
		t = arr.Elem()
		if b, ok := t.Underlying().(*types.Basic); ok && b.Info()&types.IsString != 0 {
			return onlyAccessed(alloc)
		}
	}
	if !isScope(t) && !isChange(t) {
		return false
	}
	return onlyAccessed(alloc)
}

func onlyAccessed(alloc *ssa.Alloc) bool {
	for _, r := range *alloc.Referrers() {
		switch r := r.(type) {
		case *ssa.Store:
			if r.Val == alloc {
				return false
			}
		case *ssa.UnOp:
			if r.Op != token.MUL {
				return false
			}
		case *ssa.FieldAddr:
			if r.Field != 0 || !loadsAndStores(r) {
				return false
			}
		case *ssa.IndexAddr:
			if _, ok := constInt(r.Index); !ok || !loadsAndStores(r) {
				return false
			}
		case *ssa.Slice:
		case *ssa.MakeClosure:
			fn, ok := r.Fn.(*ssa.Function)
			if !ok {
				return false
			}
			i := slices.Index(r.Bindings, ssa.Value(alloc))
			if i < 0 || i >= len(fn.FreeVars) || !onlyRead(fn.FreeVars[i]) {
				return false
			}
		case *ssa.DebugRef:
		default:
			return false
		}
	}
	return true
}

func loadsAndStores(addr ssa.Value) bool {
	for _, r := range *addr.Referrers() {
		switch r := r.(type) {
		case *ssa.Store:
			if r.Val == addr {
				return false
			}
		case *ssa.UnOp:
			if r.Op != token.MUL {
				return false
			}
		case *ssa.DebugRef:
		default:
			return false
		}
	}
	return true
}

// onlyRead reports whether a closure only reads its free variable fv.
func onlyRead(fv *ssa.FreeVar) bool {
	for _, r := range *fv.Referrers() {
		switch r := r.(type) {
		case *ssa.UnOp:
			if r.Op != token.MUL {
				return false
			}
		case *ssa.FieldAddr:
			if r.Field != 0 || !onlyLoads(r) {
				return false
			}
		case *ssa.DebugRef:
		default:
			return false
		}
	}
	return true
}

func onlyLoads(addr ssa.Value) bool {
	for _, r := range *addr.Referrers() {
		if u, ok := r.(*ssa.UnOp); !ok || u.Op != token.MUL {
			if _, ok := r.(*ssa.DebugRef); !ok {
				return false
			}
		}
	}
	return true
}

// mustRun reports whether every path of its function that returns goes through b.
func (a *analysis) mustRun(b *ssa.BasicBlock) bool {
	if m, ok := a.musts[b]; ok {
		return m
	}
	m := false
	for _, r := range b.Parent().Blocks {
		// The block a deferred call that recovers returns from runs in no order of the others.
		if len(r.Instrs) == 0 || r == b.Parent().Recover {
			continue
		}
		if _, ok := r.Instrs[len(r.Instrs)-1].(*ssa.Return); !ok {
			continue
		}
		if !b.Dominates(r) {
			m = false
			break
		}
		m = true
	}
	a.musts[b] = m
	return m
}

// implementations are the methods named m of the repositories kanna-orm generated that implement t, an interface.
func (a *analysis) implementations(t types.Type, m *types.Func) []*ssa.Function {
	key := types.TypeString(t, nil) + "." + m.Name()
	if fns, ok := a.impls[key]; ok {
		return fns
	}
	iface, ok := t.Underlying().(*types.Interface)
	var fns []*ssa.Function
	for _, r := range a.repositories {
		if !ok {
			break
		}
		var recv types.Type = r
		if !types.Implements(recv, iface) {
			recv = types.NewPointer(r)
			if !types.Implements(recv, iface) {
				continue
			}
		}
		if fn := a.prog.LookupMethod(recv, m.Pkg(), m.Name()); fn != nil {
			fns = append(fns, fn)
		}
	}
	a.impls[key] = fns
	return fns
}

// check reads fn, a function of a package vet checks, and then the closures it makes, with what their free variables
// hold.
func (a *analysis) check(fn *ssa.Function) {
	if len(fn.Blocks) == 0 || a.generated(fn) {
		return
	}
	args := make([]value, len(fn.Params))
	for i := range args {
		args[i] = unknown{}
	}
	env, ok := a.envs[fn]
	if !ok {
		env = make([]value, len(fn.FreeVars))
		for i := range env {
			env[i] = unknown{}
		}
	}
	f := a.frame(fn, args, env, cause{}, 0)
	f.root = true
	if f.run() {
		for instr, fail := range f.reports {
			a.reports = append(a.reports, report{pos: a.callPos(instr), in: displayName(fn), fail: fail})
		}
		maps.Copy(a.envs, f.envs)
	}
	for _, anon := range fn.AnonFuncs {
		a.check(anon)
	}
}
