// module writes archive into a module of its own, as writeModule does, and loads its package scopes.
func module(t *testing.T, archive string) *packages.Package {
	t.Helper()

	set, err := packages.Load([]string{"./scopes"}, packages.Config{Dir: writeModule(t, archive)})
	if err != nil {
		t.Fatal(err)
	}
	if len(set.Diags) > 0 || len(set.Packages) != 1 {
		t.Fatalf("load: %d packages, %v", len(set.Packages), set.Diags)
	}
	return set.Packages[0]
}

// TestMain loads every module the tests write outside any workspace. A GOWORK pinned by the Makefile or the
// environment would otherwise put them outside the modules it lists, which the go command refuses to load.
func TestMain(m *testing.M) {
	// Before any test runs: t.Setenv would rule out t.Parallel.
	if err := os.Setenv("GOWORK", "off"); err != nil {
		panic(err)
	}
	os.Exit(m.Run())
}

// writeModule writes the files of archive, a txtar archive, into a module of its own, example.com/shop, which
// requires this module as it is checked out, and returns its directory.
func writeModule(t *testing.T, archive string) string {
	t.Helper()
	return writeModuleGo(t, archive, "1.26.0")
}

// writeModuleGo is writeModule of a module declaring the go version goVersion.
func writeModuleGo(t *testing.T, archive, goVersion string) string {
	t.Helper()

	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	files := txtar.Parse([]byte(archive)).Files
	files = append(files, txtar.File{Name: "go.mod", Data: []byte("module example.com/shop\n\ngo " + goVersion + "\n\n" +
		"require github.com/go-kanna/orm v0.0.0\n\nreplace github.com/go-kanna/orm => " + root + "\n")})
	for _, f := range files {
		path := filepath.Join(dir, filepath.FromSlash(f.Name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, f.Data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// report renders ds as diag does, naming each file by its base name.
func report(ds []diag.Diag) string {
	lines := make([]string, 0, len(ds))
	for _, d := range ds {
		d.Pos.Filename = filepath.Base(d.Pos.Filename)
		lines = append(lines, d.String())
	}
	return strings.Join(lines, "\n")
}

