func TestFindScopes(t *testing.T) {
	t.Parallel()

	pkg := module(t, `
-- model/model.go --
package model

type Order struct{ ID int64 }

type OrderLine struct{ OrderID int64 }

type Person struct{ ID int64 }
-- scopes/scopes.go --
package scopes

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm/scope"
)

//kanna:scope table=orders
type Order struct{ q scope.Of[model.Order] }

// OrderLine is a scope of the lines of orders.
//
//kanna:scope table=order_lines
type OrderLine struct{ lines scope.Of[model.OrderLine] }

type (
	//kanna:scope table=person
	Person struct{ q scope.Of[model.Person] }

	unmarked struct{}
)

type Tag struct{ Name string }

//kanna:scope table=tags
type TagScope struct{ q scope.Of[Tag] }
-- scopes/scopes_gen.go --
// Code generated by kanna-orm. DO NOT EDIT.

package scopes

func Orders() Order { return Order{} }

//kanna:scope table=nowhere
type Generated struct{}
`)
	got, ds := gen.FindScopes(pkg, shop)
	if len(ds) > 0 {
		t.Fatalf("FindScopes:\n%s", report(ds))
	}
	want := []gen.Scope{
		// Declared by hand, none has a function returning the empty scope: its zero value is one.
		{Name: "Order", Field: "q", Model: "model.Order", Table: "orders"},
		{Name: "OrderLine", Field: "lines", Model: "model.OrderLine", Table: "order_lines"},
		{Name: "Person", Field: "q", Model: "model.Person", Table: "person"},
		{Name: "TagScope", Field: "q", Model: "scopes.Tag", Table: "tags"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("FindScopes =\n%+v\nwant\n%+v", got, want)
	}
}

func TestFindScopes_Mistakes(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name, decls, want string
	}{
		{"a directive it cannot read", `
//kanna:scope colour=red
type Order struct{ q scope.Of[model.Order] }
`, "scopes.go:10:1: error: //kanna:scope takes table=…, not \"colour=red\"\n" +
			"  as in //kanna:scope table=orders"},
		{"a model named after no table", `
//kanna:scope
type Item struct{ q scope.Of[model.Item] }
`, "scopes.go:10:1: error: Item: the snapshot has no table items, which its model is named after\n" +
			"  name its table with table=, as in //kanna:scope table=person"},
		{"a table misspelled", `
//kanna:scope table=order
type Order struct{ q scope.Of[model.Order] }
`, "scopes.go:10:1: error: Order: the snapshot has no table order\n  did you mean orders?"},
		{"a table not described", `
//kanna:scope table=invoices
type Order struct{ q scope.Of[model.Order] }
`, "scopes.go:10:1: error: Order: the snapshot has no table invoices\n" +
			"  if it is new, describe the database again: go tool kanna-orm describe"},
		// A scope type declared by hand has no function returning the empty scope, so no name of one is taken, or
		// cannot be made.
		{"a table no Go name is made of", `
//kanna:scope table=2fa_codes
type Order struct{ q scope.Of[model.Order] }
`, ""},
		{"a table named as the type", `
//kanna:scope table=person
type Person struct{ q scope.Of[model.Order] }
`, ""},
		{"a function of the table's name declared by hand", `
//kanna:scope table=orders
type Order struct{ q scope.Of[model.Order] }

func Orders() Order { return Order{} }
`, ""},
		{"a function named", `
//kanna:scope table=order_lines func=Lines
type OrderLine struct{ q scope.Of[model.Order] }
`, "scopes.go:10:1: error: //kanna:scope takes no func=: a scope type declared by hand has no function returning " +
			"the empty scope\n  its zero value, OrderLine{}, is the empty scope; " +
			"write func Lines() OrderLine { return OrderLine{} } for a function of that name"},
		{"not a struct", `
//kanna:scope table=orders
type Order int
`, "scopes.go:10:1: error: //kanna:scope marks a struct type, not a type other than a struct or an interface, so " +
			"nothing reads it\n  write it right above a struct type"},
		{"an alias", `
//kanna:scope table=orders
type Order = model.Order
`, "scopes.go:10:1: error: //kanna:scope marks a struct type, not a type alias, so nothing reads it\n" +
			"  write it right above a struct type"},
		{"a second field", `
//kanna:scope table=orders
type Order struct {
	q scope.Of[model.Order]
	n int
}
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an scope.Of of its model\n" +
			"  as in type Order struct{ q scope.Of[model.Order] }"},
		{"a field other than an scope.Of", `
//kanna:scope table=orders
type Order struct{ q model.Order }
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an scope.Of of its model\n" +
			"  as in type Order struct{ q scope.Of[model.Order] }"},
		{"generic", `
//kanna:scope table=orders
type Order[M any] struct{ q scope.Of[M] }
`, "scopes.go:11:6: error: Order: a scope type is not generic: it is the scope of one table"},
		{"an scope.Of embedded", `
//kanna:scope table=orders
type Order struct{ scope.Of[model.Order] }
`, "scopes.go:11:6: error: Order: its scope.Of is embedded, which makes Raw a method of the scope\n" +
			"  name the field: q scope.Of[model.Order]"},
		{"an scope.Of exported", `
//kanna:scope table=orders
type Order struct{ Q scope.Of[model.Order] }
`, "scopes.go:11:6: error: Order: the field Q is exported, so code outside the package could narrow it with SQL of " +
			"its own\n  unexport it: q scope.Of[model.Order]"},
		{"a pointer for a model", `
//kanna:scope table=orders
type Order struct{ q scope.Of[*model.Order] }
`, "scopes.go:11:6: error: Order: the model, *model.Order, is not a named struct\n" +
			"  hold the struct itself: scope.Of[model.Order]"},
		{"a slice for a model", `
//kanna:scope table=orders
type Order struct{ q scope.Of[[]model.Order] }
`, "scopes.go:11:6: error: Order: the model, []model.Order, is not a named struct"},
		{"what is wrong with the type and with the directive", `
//kanna:scope table=order
type Order struct{ q model.Order }
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an scope.Of of its model\n" +
			"  as in type Order struct{ q scope.Of[model.Order] }\n" +
			"scopes.go:10:1: error: Order: the snapshot has no table order\n  did you mean orders?"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			pkg := module(t, `
-- model/model.go --
package model

type Order struct{ ID int64 }

type Item struct{ ID int64 }
-- scopes/scopes.go --
package scopes

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm/scope"
)

var _ scope.Of[model.Order]
`+tt.decls)
			_, ds := gen.FindScopes(pkg, shop)
			if got := report(ds); got != tt.want {
				t.Errorf("FindScopes reports\n%s\nwant\n%s", got, tt.want)
			}
		})
	}
}

// A scope type whose model holds no field of the primary key has no paging methods, and its doc says why.
func TestEmit_ScopeOfAModelWithoutItsKey(t *testing.T) {
	t.Parallel()

	pkg := module(t, `
-- model/model.go --
package model

type Order struct{ Status string }
-- scopes/scopes.go --
package scopes

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm/scope"
)

//kanna:scope table=orders
type Order struct{ q scope.Of[model.Order] }
`)
	s := snapshot.Snapshot{Dialect: snapshot.PostgreSQL, Tables: map[string]snapshot.Table{
		"orders": {Columns: columns("id", "status"), PrimaryKey: []string{"id"}},
	}}
	src, ds, err := gen.Emit(pkg, s)
	if err != nil || len(ds) > 0 {
		t.Fatalf("Emit: %v\n%s", err, report(ds))
	}
	const why = "// It has no After, Before, Cursor, or AfterCursor, which continue a page from a row by the primary " +
		"key:\n// model.Order holds no field of id, of the primary key of orders.\nfunc (s Order) Of()"
	if !strings.Contains(string(src), why) || strings.Contains(string(src), ") After(") {
		t.Errorf("Emit wrote\n%s\nwant no After, and the doc\n%s", src, why)
	}
}
