// module writes archive into a module of its own, as writeModule does, and loads its package scopes.
func module(t *testing.T, archive string) *packages.Package {
	t.Helper()

	set, err := packages.Load([]string{"./scopes"}, packages.Config{Dir: writeModule(t, archive)})
	if err != nil {
		t.Fatal(err)
	}
	if len(set.Diags) > 0 || len(set.Packages) != 1 {
		t.Fatalf("load: %d packages, %v", len(set.Packages), set.Diags)
	}
	return set.Packages[0]
}

// writeModule writes the files of archive, a txtar archive, into a module of its own, example.com/shop, which
// requires this module as it is checked out, and returns its directory.
func writeModule(t *testing.T, archive string) string {
	t.Helper()

	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	files := txtar.Parse([]byte(archive)).Files
	files = append(files, txtar.File{Name: "go.mod", Data: []byte("module example.com/shop\n\ngo 1.26.0\n\n" +
		"require github.com/go-kanna/orm v0.0.0\n\nreplace github.com/go-kanna/orm => " + root + "\n")})
	for _, f := range files {
		path := filepath.Join(dir, filepath.FromSlash(f.Name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, f.Data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// report renders ds as diag does, naming each file by its base name.
func report(ds []diag.Diag) string {
	lines := make([]string, 0, len(ds))
	for _, d := range ds {
		d.Pos.Filename = filepath.Base(d.Pos.Filename)
		lines = append(lines, d.String())
	}
	return strings.Join(lines, "\n")
}

var shop = snapshot.Snapshot{
	Dialect: snapshot.PostgreSQL,
	Tables: map[string]snapshot.Table{
		"orders":      {},
		"order_lines": {},
		"person":      {},
		"tags":        {},
		"2fa_codes":   {},
	},
}

func TestFindScopes(t *testing.T) {
	t.Parallel()

	pkg := module(t, `
-- model/model.go --
package model

type Order struct{ ID int64 }

type OrderLine struct{ OrderID int64 }

type Person struct{ ID int64 }
-- scopes/scopes.go --
package scopes

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm"
)

//kanna:scope table=orders
type Order struct{ q orm.Of[model.Order] }

// OrderLine is a scope of the lines of orders.
//
//kanna:scope table=order_lines func=Lines
type OrderLine struct{ lines orm.Of[model.OrderLine] }

type (
	//kanna:scope table=person func=People
	Person struct{ q orm.Of[model.Person] }

	unmarked struct{}
)

type Tag struct{ Name string }

//kanna:scope table=tags
type TagScope struct{ q orm.Of[Tag] }
-- scopes/orm_gen.go --
// Code generated by kanna-orm. DO NOT EDIT.

package scopes

func Orders() Order { return Order{} }

//kanna:scope table=nowhere
type Generated struct{}
`)
	got, ds := gen.FindScopes(pkg, shop)
	if len(ds) > 0 {
		t.Fatalf("FindScopes:\n%s", report(ds))
	}
	want := []gen.Scope{
		{Name: "Order", Field: "q", Model: "model.Order", Table: "orders", Func: "Orders"},
		{Name: "OrderLine", Field: "lines", Model: "model.OrderLine", Table: "order_lines", Func: "Lines"},
		{Name: "Person", Field: "q", Model: "model.Person", Table: "person", Func: "People"},
		{Name: "TagScope", Field: "q", Model: "scopes.Tag", Table: "tags", Func: "Tags"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("FindScopes =\n%+v\nwant\n%+v", got, want)
	}
}

func TestFindScopes_Mistakes(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name, decls, want string
	}{
		{"a directive it cannot read", `
//kanna:scope
type Order struct{ q orm.Of[model.Order] }
`, "scopes.go:10:1: error: //kanna:scope wants the table its type is a scope of\n  as in //kanna:scope table=orders"},
		{"a table misspelled", `
//kanna:scope table=order
type Order struct{ q orm.Of[model.Order] }
`, "scopes.go:10:1: error: Order: the snapshot has no table order\n  did you mean orders?"},
		{"a table not described", `
//kanna:scope table=invoices
type Order struct{ q orm.Of[model.Order] }
`, "scopes.go:10:1: error: Order: the snapshot has no table invoices\n" +
			"  if it is new, describe the database again: go tool kanna-orm describe"},
		{"a table no Go name is made of", `
//kanna:scope table=2fa_codes
type Order struct{ q orm.Of[model.Order] }
`, "scopes.go:10:1: error: Order: no Go name can be made of 2fa_codes\n" +
			"  name the function returning the empty scope with func="},
		{"a function named as the type", `
//kanna:scope table=person
type Person struct{ q orm.Of[model.Order] }
`, "scopes.go:10:1: error: Person: the function returning the empty scope would be named Person, as the type is\n" +
			"  name another with func="},
		{"a function declared already", `
//kanna:scope table=orders
type Order struct{ q orm.Of[model.Order] }

func Orders() Order { return Order{} }
`, "scopes.go:10:1: error: Order: Orders, the function returning the empty scope, is declared already\n" +
			"  it is declared at scopes.go:13\n  name another with func="},
		{"a function of two scope types", `
//kanna:scope table=orders
type Order struct{ q orm.Of[model.Order] }

//kanna:scope table=order_lines func=Orders
type OrderLine struct{ q orm.Of[model.Order] }
`, "scopes.go:13:1: error: OrderLine: Orders is the function returning the empty scope of Order too\n" +
			"  name another with func="},
		{"not a struct", `
//kanna:scope table=orders
type Order int
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an orm.Of of its model\n" +
			"  as in type Order struct{ q orm.Of[model.Order] }"},
		{"an alias", `
//kanna:scope table=orders
type Order = model.Order
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an orm.Of of its model\n" +
			"  as in type Order struct{ q orm.Of[model.Order] }"},
		{"a second field", `
//kanna:scope table=orders
type Order struct {
	q orm.Of[model.Order]
	n int
}
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an orm.Of of its model\n" +
			"  as in type Order struct{ q orm.Of[model.Order] }"},
		{"a field other than an orm.Of", `
//kanna:scope table=orders
type Order struct{ q model.Order }
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an orm.Of of its model\n" +
			"  as in type Order struct{ q orm.Of[model.Order] }"},
		{"generic", `
//kanna:scope table=orders
type Order[M any] struct{ q orm.Of[M] }
`, "scopes.go:11:6: error: Order: a scope type is not generic: it is the scope of one table"},
		{"an orm.Of embedded", `
//kanna:scope table=orders
type Order struct{ orm.Of[model.Order] }
`, "scopes.go:11:6: error: Order: its orm.Of is embedded, which makes Where a method of the scope\n" +
			"  name the field: q orm.Of[model.Order]"},
		{"an orm.Of exported", `
//kanna:scope table=orders
type Order struct{ Q orm.Of[model.Order] }
`, "scopes.go:11:6: error: Order: the field Q is exported, so code outside the package could narrow it with SQL of " +
			"its own\n  unexport it: q orm.Of[model.Order]"},
		{"a pointer for a model", `
//kanna:scope table=orders
type Order struct{ q orm.Of[*model.Order] }
`, "scopes.go:11:6: error: Order: the model, *model.Order, is not a named struct\n" +
			"  hold the struct itself: orm.Of[model.Order]"},
		{"a slice for a model", `
//kanna:scope table=orders
type Order struct{ q orm.Of[[]model.Order] }
`, "scopes.go:11:6: error: Order: the model, []model.Order, is not a named struct"},
		{"what is wrong with the type and with the directive", `
//kanna:scope table=order
type Order int
`, "scopes.go:11:6: error: Order: a scope type is a struct whose only field is an orm.Of of its model\n" +
			"  as in type Order struct{ q orm.Of[model.Order] }\n" +
			"scopes.go:10:1: error: Order: the snapshot has no table order\n  did you mean orders?"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			pkg := module(t, `
-- model/model.go --
package model

type Order struct{ ID int64 }
-- scopes/scopes.go --
package scopes

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm"
)

var _ orm.Of[model.Order]
`+tt.decls)
			_, ds := gen.FindScopes(pkg, shop)
			if got := report(ds); got != tt.want {
				t.Errorf("FindScopes reports\n%s\nwant\n%s", got, tt.want)
			}
		})
	}
}
