package gen_test

import (
	"testing"

	"github.com/go-kanna/orm/internal/gen"
	"github.com/go-kanna/orm/internal/snapshot"
	"github.com/go-kanna/orm/internal/sqlfile"
)

func TestEmit_NamesTakenAlready(t *testing.T) {
	t.Parallel()

	tests := []struct {
		// scopes is what scopes.go declares besides the scope type of orders, sql its .sql file, and old an
		// orm_gen.go an earlier run wrote.
		name, field, scopes, sql, old, want string
	}{
		{name: "a method named as one of a column", scopes: "func (s Order) IDEq(id int64) Order { return s }\n",
			want: "scopes.go:11:16: error: Order.IDEq: kanna-orm writes a method of this name, for the column id\n" +
				"  name yours otherwise"},
		{name: "a method named as one of every scope type", scopes: "func (s Order) Limit() Order { return s }\n",
			want: "scopes.go:11:16: error: Order.Limit: kanna-orm writes a method of this name, for every scope type\n" +
				"  name yours otherwise"},
		{name: "a method named as a scope written by hand", scopes: "func (s Order) Open() Order { return s }\n",
			sql: "-- scope: Order.Open()\nid > 0\n",
			want: "scopes.go:11:16: error: Order.Open: kanna-orm writes a method of this name, for the scope " +
				"order_scopes.sql writes\n  name yours otherwise"},
		{name: "a scope written by hand named as a method of a column", sql: "-- scope: Order.IDGt(n int64)\nid > :n\n",
			want: "order_scopes.sql:1:1: error: -- scope: Order.IDGt: kanna-orm writes a method of this name, for the " +
				"column id\n  name the scope otherwise"},
		{name: "a field named as a method", field: "values",
			want: "scopes.go:8:1: error: Order: its field values is named as a method kanna-orm writes, to continue " +
				"a page from a row\n  name the field otherwise"},
		{name: "a method kanna-orm wrote before", old: "func (s Order) IDEq(id int64) Order { return s }\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			field := tt.field
			if field == "" {
				field = "q"
			}
			archive := `
-- model/model.go --
package model

type Order struct{ ID int64 }
-- scopes/scopes.go --
package scopes

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm"
)

//kanna:scope table=orders
type Order struct{ ` + field + ` orm.Of[model.Order] }

` + tt.scopes + `
-- scopes/order_scopes.sql --
` + tt.sql
			if tt.old != "" {
				archive += "-- scopes/orm_gen.go --\n// Code generated by kanna-orm. DO NOT EDIT.\n\npackage scopes\n\n" + tt.old
			}
			pkg := module(t, archive)
			stmts, _ := sqlfile.Parse("order_scopes.sql", []byte(tt.sql))
			described := map[string]snapshot.Statement{}
			for _, st := range stmts {
				described["example.com/shop/scopes."+st.Type+"."+st.Name] = snapshot.Statement{
					Digest: snapshot.Digest(st.Text),
				}
			}
			s := snapshot.Snapshot{Dialect: snapshot.PostgreSQL, Statements: described, Tables: map[string]snapshot.Table{
				"orders": {Columns: columns("id"), PrimaryKey: []string{"id"}},
			}}
			_, ds, err := gen.Emit(pkg, s)
			if err != nil {
				t.Fatal(err)
			}
			if got := report(ds); got != tt.want {
				t.Errorf("Emit reports\n%s\nwant\n%s", got, tt.want)
			}
		})
	}
}
