func TestIndex(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, `
-- shop.go --
package shop

import (
	"example.com/shop/catalog/v2"
	"github.com/go-kanna/orm"
)

//kanna:scope table=products
type Product struct{ q orm.Of[catalog.Product] }
-- catalog/v2/catalog.go --
package catalog

type Product struct{ ID int64 }
-- model/model.go --
package model

type (
	Order     struct{ ID int64 }
	OrderLine struct{ ID int64 }
)
-- scopes/scopes.go --
package scopes

import (
	m "example.com/shop/model"
	o "github.com/go-kanna/orm"
)

//kanna:scope table=orders
type Order struct{ q o.Of[m.Order] }

type (
	//kanna:scope table=order_lines
	OrderLine struct{ q o.Of[m.OrderLine] }
)

//kanna:scope table=tags
type Tag struct{ q o.Of[tag] }

type tag struct{ Name string }

//kanna:scope table=broken
type Broken struct{ q m.Order }
-- scopes/scopes_test.go --
package scopes

//kanna:scope table=tests
type Test struct{ q o.Of[m.Order] }
-- scopes/orm_gen.go --
// Code generated by kanna-orm. DO NOT EDIT.

package scopes

//kanna:scope table=generated
type Generated struct{ q o.Of[m.Order] }
-- scopes/plain.go --
package scopes

// Plain mentions //kanna:scope, but in its doc only.
type Plain struct{}
-- testdata/scopes.go --
package scopes

//kanna:scope table=testdata
type Order struct{ q orm.Of[model.Order] }
-- vendor/example.com/other/scopes.go --
package other

//kanna:scope table=vendored
type Order struct{ q orm.Of[model.Order] }
-- .hidden/scopes.go --
package hidden

//kanna:scope table=hidden
type Order struct{ q orm.Of[model.Order] }
-- _old/scopes.go --
package old

//kanna:scope table=old
type Order struct{ q orm.Of[model.Order] }
-- nested/go.mod --
module example.com/nested
-- nested/scopes.go --
package nested

//kanna:scope table=nested
type Order struct{ q orm.Of[model.Order] }
-- unparsable/scopes.go --
package unparsable

//kanna:scope table=unparsable
type Order struct{
`)
	got, err := gen.Index(filepath.Join(dir, "scopes"), nil)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"example.com/shop/scopes.Order example.com/shop/model.Order orders scopes.go:8",
		"example.com/shop/scopes.OrderLine example.com/shop/model.OrderLine order_lines scopes.go:12",
		"example.com/shop/scopes.Tag example.com/shop/scopes.tag tags scopes.go:16",
		"example.com/shop.Product example.com/shop/catalog/v2.Product products ../shop.go:8",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Index =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func TestIndex_NoModule(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	if _, err := gen.Index(dir, nil); err == nil || !strings.Contains(err.Error(), "no go.mod in "+dir+" or above it") {
		t.Errorf("Index(%s) error = %v, want no go.mod", dir, err)
	}
}

func TestCheckUnique(t *testing.T) {
	t.Parallel()

	pkg := module(t, `
-- model/model.go --
package model

type (
	Order     struct{ ID int64 }
	OrderLine struct{ ID int64 }
	Line      struct{ ID int64 }
	Customer  struct{ ID int64 }
	Client    struct{ ID int64 }
)
-- admin/admin.go --
package admin

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm"
)

//kanna:scope table=orders_archive
type Order struct{ q orm.Of[model.Order] }

//kanna:scope table=customers
type Customer struct{ q orm.Of[model.Customer] }
-- scopes/scopes.go --
package scopes

import (
	"example.com/shop/model"
	"github.com/go-kanna/orm"
)

//kanna:scope table=orders
type Order struct{ q orm.Of[model.Order] }

//kanna:scope table=order_lines
type OrderLine struct{ q orm.Of[model.OrderLine] }

//kanna:scope table=order_lines func=Lines
type Line struct{ q orm.Of[model.Line] }

//kanna:scope table=customers func=Clients
type Client struct{ q orm.Of[model.Client] }

//kanna:scope table=line_items
type LineItem struct{ q orm.Of[model.OrderLine] }
`)
	s := snapshot.Snapshot{Dialect: snapshot.PostgreSQL, Tables: map[string]snapshot.Table{
		"orders": {}, "orders_archive": {}, "order_lines": {}, "customers": {}, "line_items": {},
	}}
	ds, err := gen.CheckUnique(pkg, s)
	if err != nil {
		t.Fatal(err)
	}
	const rule = "\n  a table has one scope type, and a model belongs to one table"
	want := "scopes.go:8:1: error: Order: admin.Order is a scope type of model.Order too\n" +
		"  it is declared in example.com/shop/admin, at admin.go:8" + rule + "\n" +
		"scopes.go:14:1: error: Line: OrderLine is a scope type of the table order_lines too\n" +
		"  it is declared at scopes.go:11" + rule + "\n" +
		"scopes.go:17:1: error: Client: admin.Customer is a scope type of the table customers too\n" +
		"  it is declared in example.com/shop/admin, at admin.go:11" + rule + "\n" +
		"scopes.go:20:1: error: LineItem: OrderLine is a scope type of model.OrderLine too\n" +
		"  it is declared at scopes.go:11" + rule
	if got := report(ds); got != want {
		t.Errorf("CheckUnique reports\n%s\nwant\n%s", got, want)
	}
}
