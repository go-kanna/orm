// enumArrays holds tickets in a column of an enum type of PostgreSQL, which no type is registered for, and writes and
// reads them by arrays of its values.
const enumArrays = `
-- store/store.go --
package store

import "context"

//kanna:scopes model-package=.

type State string

type Ticket struct {
	ID    string
	State State
	Prior *State
}

type Note struct {
	ID    int64
	State State
}

//kanna:repository
type TicketRepository interface {
	Insert(ctx context.Context, ts []Ticket) error
	List(ctx context.Context, s ...TicketScope) ([]Ticket, error)
	ListByStates(ctx context.Context, states []State) ([]Ticket, error)
}

//kanna:repository
type NoteRepository interface {
	Insert(ctx context.Context, ns []Note) error
	List(ctx context.Context, s ...NoteScope) ([]Note, error)
}
-- impl/queries.sql --
-- query: ListByStates
SELECT id, state, prior FROM tickets WHERE state = ANY(:states::text[]::"Ticket State"[]) ORDER BY id;
-- impl/impl_test.go --
package impl

import (
	"slices"
	"testing"

	"example.com/shop/store"
)

func ids(ts []store.Ticket) []string {
	var out []string
	for _, t := range ts {
		out = append(out, t.ID)
	}
	return out
}

func TestTickets(t *testing.T) {
	ctx := t.Context()
	db := open(t)
	repo := NewTicketRepository(db)
	closed := store.State("closed")
	tickets := []store.Ticket{{"a", "open", nil}, {"b", "closed", nil}, {"c", "on hold", &closed}}
	if err := repo.Insert(ctx, tickets); err != nil {
		t.Fatal(err)
	}
	for _, tt := range []struct {
		name  string
		scope store.TicketScope
		want  []string
	}{
		{"In", store.Tickets().StateIn("open", "on hold"), []string{"a", "c"}},
		{"In of none", store.Tickets().StateIn(), nil},
		{"NotIn", store.Tickets().StateNotIn("open"), []string{"b", "c"}},
		{"NotIn of none", store.Tickets().StateNotIn(), []string{"a", "b", "c"}},
		{"In of a nullable column", store.Tickets().PriorIn("closed"), []string{"c"}},
	} {
		got, err := repo.List(ctx, tt.scope.IDAsc())
		if err != nil || !slices.Equal(ids(got), tt.want) {
			t.Errorf("%s = %v, %v, want %v", tt.name, ids(got), err, tt.want)
		}
	}
	got, err := repo.ListByStates(ctx, []store.State{"closed", "on hold"})
	if err != nil || !slices.Equal(ids(got), []string{"b", "c"}) {
		t.Errorf("ListByStates = %v, %v", ids(got), err)
	}
	if got, err := repo.ListByStates(ctx, nil); err != nil || len(got) != 0 {
		t.Errorf("ListByStates(nil) = %v, %v", ids(got), err)
	}

	notes := NewNoteRepository(db)
	if err := notes.Insert(ctx, []store.Note{{State: "open"}, {ID: 10, State: "closed"}}); err != nil {
		t.Fatal(err)
	}
	if got, err := notes.List(ctx, store.Notes().StateIn("closed")); err != nil || len(got) != 1 || got[0].ID != 10 {
		t.Errorf("the closed notes = %+v, %v", got, err)
	}
}
`

const enumArraysSchema = `
CREATE TYPE "Ticket State" AS ENUM ('open', 'closed', 'on hold');
CREATE TABLE tickets (id text PRIMARY KEY, state "Ticket State" NOT NULL, prior "Ticket State");
CREATE TABLE notes (id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
	state "Ticket State" NOT NULL);
`

// TestCommand_EnumArraysPostgres writes and narrows rows by arrays of the values of an enum type, through pgx and
// database/sql, with no type registered on the connection.
func TestCommand_EnumArraysPostgres(t *testing.T) {
	t.Parallel()
	url := os.Getenv("KANNA_ORM_TEST_POSTGRES")
	if url == "" {
		t.Skip("integration database is not configured")
	}

	for _, driver := range []string{"pgx", "database/sql"} {
		t.Run(driver, func(t *testing.T) {
			t.Parallel()
			schema := fmt.Sprintf("kanna_enum_arrays_%d", time.Now().UnixNano())
			db, err := sql.Open("pgx", url)
			if err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() {
				_, _ = db.ExecContext(context.WithoutCancel(t.Context()), "DROP SCHEMA "+schema+" CASCADE")
				_ = db.Close()
			})
			if _, err := db.ExecContext(t.Context(), "CREATE SCHEMA "+schema+"; SET search_path TO "+schema+";"+
				enumArraysSchema); err != nil {
				t.Fatal(err)
			}

			url := schemaURL(url, schema)
			open := `
-- impl/open_test.go --
package impl

import (
	"database/sql"
	"testing"

	_ "github.com/jackc/pgx/v5/stdlib"
)

func open(t *testing.T) DBTX {
	db, err := sql.Open("pgx", "` + url + `")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	return db
}
`
			if driver == "pgx" {
				open = `
-- impl/open_test.go --
package impl

import (
	"context"
	"testing"

	"github.com/jackc/pgx/v5"
)

func open(t *testing.T) DBTX {
	conn, err := pgx.Connect(t.Context(), "` + url + `")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = conn.Close(context.Background()) })
	return conn
}
`
			}
			dir := writeModule(t, enumArrays+open)
			describeRelationKeys(t, dir, url)
			code, _, errOut := run(t, filepath.Join(dir, "store"), "-destination", "../impl", "-driver", driver)
			if code != cli.ExitOK {
				t.Fatalf("kanna-orm = %d\n%s", code, errOut)
			}
			moduleCommand(t, dir, "test", "-mod=mod", "./...")
		})
	}
}
